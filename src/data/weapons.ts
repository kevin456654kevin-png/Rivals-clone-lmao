export function weaponsByCategory(category: WeaponDef['category'], banned: string[]) {
  return WEAPONS.filter((w) => w.category === category && !banned.includes(w.id));
}

export function getWeapon(id: string | null | undefined): WeaponDef | undefined {
  if (!id) return undefined;
  return WEAPONS.find((w) => w.id === id);
}
